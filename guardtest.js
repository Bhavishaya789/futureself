const { createGuard } = require('./app/core/videoguard');
const VG = require('./app/renderer/js/vguard');
const g = createGuard(); let fail = 0;
const ok = (n, c) => { console.log(c ? 'PASS' : 'FAIL', n); if (!c) fail++; };
const A = 'aaaaaaaaaaa', B = 'bbbbbbbbbbb';
const chk = (url, body, rt) => g.check({ url, resourceType: rt || 'xhr', uploadData: body ? [{ bytes: Buffer.from(JSON.stringify(body)) }] : undefined }).cancel;
ok('nothing allowed yet: embed blocked', chk('https://www.youtube-nocookie.com/embed/' + A, null, 'subFrame') === true);
g.allow(A);
ok('chosen video embed allowed', chk('https://www.youtube-nocookie.com/embed/' + A + '?rel=0', null, 'subFrame') === false);
ok('other video embed blocked', chk('https://www.youtube-nocookie.com/embed/' + B, null, 'subFrame') === true);
ok('watch page blocked', chk('https://www.youtube.com/watch?v=' + B, null, 'mainFrame') === true);
ok('results (search) page blocked', chk('https://www.youtube.com/results?search_query=x', null, 'mainFrame') === true);
ok('channel page blocked', chk('https://www.youtube.com/@someone', null, 'mainFrame') === true);
ok('shorts blocked', chk('https://www.youtube.com/shorts/' + B, null, 'mainFrame') === true);
ok('playlist blocked', chk('https://www.youtube.com/playlist?list=PL1', null, 'mainFrame') === true);
ok('youtube home blocked? (root not in list but not allowed in embed context)', chk('https://www.youtube.com/', null, 'mainFrame') === true);
ok('search api blocked', chk('https://www.youtube.com/youtubei/v1/search?key=k', { query: 'x' }) === true);
ok('browse api blocked', chk('https://www.youtube.com/youtubei/v1/browse', {}) === true);
ok('player api for chosen video allowed', chk('https://www.youtube.com/youtubei/v1/player?key=k', { videoId: A }) === false);
ok('player api for another video blocked', chk('https://www.youtube.com/youtubei/v1/player?key=k', { videoId: B }) === true);
ok('next api for another video blocked', chk('https://www.youtube.com/youtubei/v1/next', { videoId: B }) === true);
ok('log_event without videoId allowed', chk('https://www.youtube.com/youtubei/v1/log_event', { x: 1 }) === false);
ok('non-youtube host untouched', chk('https://example.com/watch?v=1') === false);
ok('look-alike host not treated as youtube (no false allow of youtube)', chk('https://youtube.com.evil.com/embed/' + B) === false);
ok('bad id rejected by allow()', g.allow('short') === null && g.current() === null);
g.allow(A);
const m = (o) => JSON.stringify(o);
ok('player msg same video -> ok', VG.decide(m({ event: 'infoDelivery', info: { playerState: 1, videoData: { video_id: A } } }), A) === 'ok');
ok('player msg other video -> wrong', VG.decide(m({ event: 'infoDelivery', info: { videoData: { video_id: B } } }), A) === 'wrong');
ok('state 0 -> ended', VG.decide(m({ event: 'onStateChange', info: 0 }), A) === 'ended');
ok('infoDelivery ended -> ended', VG.decide(m({ event: 'infoDelivery', info: { playerState: 0, videoData: { video_id: A } } }), A) === 'ended');
ok('junk -> ok', VG.decide('hello', A) === 'ok' && VG.decide(null, A) === 'ok' && VG.decide({}, A) === 'ok');
console.log(fail ? 'FAILED ' + fail : 'ALL PASS'); process.exit(fail ? 1 : 0);
