#!/usr/bin/env python3
"""Builds website/api/_codebank2.js : the HARD questions (with hidden tests) used by the 5-question coding challenge.
Source: app/renderer/data/ct/*.js. Run: python3 tools/build-codebank2.py"""
import json, re, glob, os
out = {}
for f in sorted(glob.glob('app/renderer/data/ct/*.js')):
    sid = os.path.basename(f)[:-3]
    if sid in ('index', 'cs11', 'cs12'): continue
    d = json.loads(re.search(r'=(\{.*\});$', open(f, encoding='utf8').read(), re.S).group(1))
    S = {'title': d['title'], 'lang': d.get('lang'), 'topics': {}}
    for t in d['topics']:
        hs = [{k: i[k] for k in ('id', 'title', 'statement', 'input', 'output', 'samples', 'tests') if k in i} for i in t['items'] if i['level'] == 'Hard']
        if len(hs) >= 5: S['topics'][t['id']] = {'title': t['title'], 'items': hs}
    out[sid] = S
js = "'use strict';\n/* FutureSelf 5-question coding challenge: HARD questions per topic. GENERATED by tools/build-codebank2.py - do not edit by hand.\n   Hidden tests live ONLY here (server side). */\nmodule.exports = " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n"
open('website/api/_codebank2.js', 'w', encoding='utf8').write(js)
print(len(js), {k: len(v['topics']) for k, v in out.items()})
